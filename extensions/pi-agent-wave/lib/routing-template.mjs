export const DELEGATE_GRAPH_ROLES = Object.freeze(["thinker", "implementer", "reviewer", "tester", "auditor", "searcher"]);
export const REQUIRED_TIERS = Object.freeze(["tools", "coding", "test", "review", "reasoning", "long-context"]);
export const OPTIONAL_TIERS = Object.freeze(["local-fast"]);

/** Standard thinking/session defaults and labels for every supported tier. */
export const TIER_DEFAULTS = Object.freeze({
	tools: { thinking: "off", session: false, label: "File search, grep, MCP calls, data processing, test runs" },
	coding: { thinking: "high", session: true, label: "Production code generation and feature implementation" },
	test: { thinking: "low", session: false, label: "Test authoring, verification, and report checks" },
	review: { thinking: "xhigh", session: true, label: "Independent code and design review" },
	reasoning: { thinking: "high", session: true, label: "Solution discovery, requirements, architecture, planning" },
	"long-context": { thinking: "medium", session: true, label: "Large-codebase and long-document tasks" },
	"local-fast": { thinking: "off", session: false, label: "Zero-cost quick operations and high-volume tasks" },
});

/** Each Delegate Graph role pins to a standard tier. */
export const ROLE_TIERS = Object.freeze({
	thinker: "reasoning",
	implementer: "coding",
	reviewer: "review",
	tester: "test",
	auditor: "review",
	searcher: "tools",
});

/** Capability-floor name each role declares in the generated routing. */
export const ROLE_CAPABILITY_FLOORS = Object.freeze({
	thinker: "planning",
	implementer: "implementation",
	reviewer: "independent_review",
	tester: "verification",
	auditor: "independent_review",
	searcher: "routine_tools",
});

/** Capability-floor -> tier map used by the adaptive router's floor promotion. */
export const CAPABILITY_FLOORS = Object.freeze({
	routine_tools: "tools",
	planning: "reasoning",
	architecture: "reasoning",
	implementation: "coding",
	domain_execution: "coding",
	independent_review: "review",
	verification: "test",
	technical_verification: "test",
	creative_review: "review",
	media_execution: "test",
	render_execution: "test",
	long_context: "long-context",
});

const HEADER = [
	"// Delegate Graph model routing, generated by pi-agent-wave-init.",
	"// Format: provider/model-id. Model order is cheapest suitable first, strongest fallback last.",
	"// Re-run `pi-agent-wave-init apply` to regenerate; `--force` backs this file up first.",
].join("\n");

/**
 * Deterministically generate the routing JSONC for the given per-tier model
 * chains. Determinism matters: re-applying the same selections must produce
 * byte-identical output so the initializer can report "no content change".
 */
export function generateRoutingTemplate(options = {}) {
	const chains = options.chains ?? {};
	const includeLocalFast = options.includeLocalFast === true;
	const tiers = {};
	for (const tier of [...REQUIRED_TIERS, ...(includeLocalFast ? OPTIONAL_TIERS : [])]) {
		const defaults = TIER_DEFAULTS[tier];
		tiers[tier] = {
			label: defaults.label,
			models: (chains[tier] ?? []).map((id) => String(id)),
			thinking: defaults.thinking,
			session: defaults.session,
		};
	}
	const roles = {};
	for (const role of DELEGATE_GRAPH_ROLES) {
		roles[role] = { tier: ROLE_TIERS[role], capability_floor: ROLE_CAPABILITY_FLOORS[role] };
	}
	const document = {
		description: [
			"Task-type model routing. Add or remove tier keys as needed.",
			"Format: provider/model-id. Model order is cheapest suitable first, strongest fallback last.",
		],
		tiers,
		adaptive: {
			enabled_by_default: true,
			capability_floors: { ...CAPABILITY_FLOORS },
		},
		roles,
		default_tier: "tools",
	};
	return `${HEADER}\n${JSON.stringify(document, null, 2)}\n`;
}
